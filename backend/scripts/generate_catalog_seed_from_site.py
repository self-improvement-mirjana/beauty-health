#!/usr/bin/env python3
"""Generate catalog seed SQL from beauty-health.rs public WooCommerce APIs."""

from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
import re
import urllib.parse
import urllib.error
import urllib.request

OUT = Path(__file__).resolve().parent.parent / "src/main/resources/db/changelog/sql/catalog-seed.sql"
TS = "TIMESTAMP '2026-01-01 12:00:00'"
BASE = "https://beauty-health.rs"


@dataclass(frozen=True)
class StoreLocation:
    id: int
    name: str
    slug: str


LOCATIONS = [
    StoreLocation(id=1, name="Magacin 1", slug="magacin-1"),
    StoreLocation(id=2, name="Magacin 2", slug="magacin-2"),
    StoreLocation(id=3, name="Magacin 3", slug="magacin-3"),
]


def esc(value: str) -> str:
    return value.replace("'", "''")


def clean_html(value: str | None, limit: int) -> str:
    if not value:
        return ""
    text = re.sub(r"<[^>]+>", " ", value)
    text = text.replace("&nbsp;", " ").replace("&amp;", "&")
    text = re.sub(r"\s+", " ", text).strip()
    return text[:limit]


def unique_slug(slug: str, fallback: str, used: set[str]) -> str:
    base = (slug or fallback).strip().lower()
    base = re.sub(r"[^a-z0-9\-]+", "-", base)
    base = re.sub(r"-{2,}", "-", base).strip("-")
    if not base:
        base = fallback
    candidate = base
    n = 2
    while candidate in used:
        candidate = f"{base}-{n}"
        n += 1
    used.add(candidate)
    return candidate


def fetch_brands() -> list[dict]:
    page = 1
    all_rows: list[dict] = []
    while True:
        url = f"{BASE}/wp-json/wp/v2/product_brand?per_page=100&page={page}"
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "beauty-health-importer/1.0"})
            with urllib.request.urlopen(req, timeout=30) as resp:
                rows = json.loads(resp.read().decode("utf-8"))
                total_pages = int(resp.headers.get("X-WP-TotalPages", str(page)))
        except urllib.error.HTTPError as exc:
            if exc.code == 400:
                break
            raise
        if not rows:
            break
        all_rows.extend(rows)
        if page >= total_pages:
            break
        page += 1
    return all_rows


def fetch_categories() -> list[dict]:
    url = f"{BASE}/wp-json/wc/store/v1/products/categories"
    req = urllib.request.Request(url, headers={"User-Agent": "beauty-health-importer/1.0"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def fetch_products() -> list[dict]:
    page = 1
    all_rows: list[dict] = []
    while True:
        params = urllib.parse.urlencode({"per_page": 100, "page": page})
        url = f"{BASE}/wp-json/wc/store/v1/products?{params}"
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "beauty-health-importer/1.0"})
            with urllib.request.urlopen(req, timeout=45) as resp:
                rows = json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            if exc.code == 400:
                break
            raise
        if not rows:
            break
        all_rows.extend(rows)
        page += 1
    return all_rows


def first_product_image_url(product: dict) -> str | None:
    imgs = product.get("images") or []
    if not imgs or not isinstance(imgs, list):
        return None
    first = imgs[0]
    if not isinstance(first, dict):
        return None
    src = first.get("src")
    if not src:
        return None
    s = str(src).strip()
    if not s:
        return None
    return s[:2048]


def cents_to_decimal(raw: str | None) -> str:
    if not raw:
        return "0.00"
    try:
        cents = int(raw)
    except ValueError:
        return "0.00"
    return f"{cents / 100:.2f}"


def main() -> None:
    brands = fetch_brands()
    categories = fetch_categories()
    products = fetch_products()

    lines: list[str] = []
    lines.append("-- B04 catalog seed (generated by scripts/generate_catalog_seed_from_site.py)\n")

    for location in LOCATIONS:
        lines.append(
            "INSERT INTO store_location (id, name, slug, is_active, created_at, updated_at) "
            f"VALUES ({location.id}, '{esc(location.name)}', '{esc(location.slug)}', true, {TS}, {TS});\n"
        )

    brand_slug_used: set[str] = set()
    brand_id_map: dict[int, int] = {}
    next_brand_id = 1
    for b in sorted(brands, key=lambda row: row.get("name", "").lower()):
        source_id = int(b["id"])
        slug = unique_slug(str(b.get("slug") or ""), f"brand-{source_id}", brand_slug_used)
        name = str(b.get("name") or slug)
        brand_id_map[source_id] = next_brand_id
        lines.append(
            "INSERT INTO brand (id, name, slug, created_at, updated_at) "
            f"VALUES ({next_brand_id}, '{esc(name)}', '{esc(slug)}', {TS}, {TS});\n"
        )
        next_brand_id += 1

    unknown_brand_id = next_brand_id
    lines.append(
        "INSERT INTO brand (id, name, slug, created_at, updated_at) "
        f"VALUES ({unknown_brand_id}, 'Unknown', 'unknown', {TS}, {TS});\n"
    )
    next_brand_id += 1

    category_slug_used: set[str] = set()
    category_id_map: dict[int, int] = {}
    next_category_id = 1
    for c in sorted(categories, key=lambda row: (int(row.get("parent") or 0), row.get("name", "").lower())):
        source_id = int(c["id"])
        slug = unique_slug(str(c.get("slug") or ""), f"category-{source_id}", category_slug_used)
        category_id_map[source_id] = next_category_id
        parent_source = int(c.get("parent") or 0)
        parent_new = category_id_map.get(parent_source)
        parent_sql = "NULL" if parent_new is None else str(parent_new)
        description = clean_html(c.get("description"), 3900)
        desc_sql = "NULL" if not description else f"'{esc(description)}'"
        lines.append(
            "INSERT INTO category (id, name, slug, description, parent_category_id, sort_order, is_active, created_at, updated_at) "
            f"VALUES ({next_category_id}, '{esc(str(c.get('name') or slug))}', '{esc(slug)}', {desc_sql}, {parent_sql}, {next_category_id}, true, {TS}, {TS});\n"
        )
        next_category_id += 1

    product_slug_used: set[str] = set()
    sku_used: set[str] = set()
    brand_logo_url: dict[int, str] = {}
    product_id = 1
    variant_id = 1
    inventory_id = 1

    for p in products:
        source_product_id = int(p["id"])
        title = clean_html(p.get("name"), 250) or f"Product {source_product_id}"
        slug = unique_slug(str(p.get("slug") or ""), f"product-{source_product_id}", product_slug_used)
        description = clean_html(p.get("description"), 3900)
        short_description = clean_html(p.get("short_description"), 480)
        desc_sql = "NULL" if not description else f"'{esc(description)}'"
        short_sql = "NULL" if not short_description else f"'{esc(short_description)}'"
        featured = str(bool(p.get("featured"))).lower()
        active = "true"

        product_brands = p.get("brands") or []
        if product_brands:
            source_brand_id = int(product_brands[0]["id"])
            mapped_brand_id = brand_id_map.get(source_brand_id, unknown_brand_id)
        else:
            mapped_brand_id = unknown_brand_id

        primary_image = first_product_image_url(p)
        img_sql = "NULL" if not primary_image else f"'{esc(primary_image)}'"
        if primary_image and mapped_brand_id not in brand_logo_url:
            brand_logo_url[mapped_brand_id] = primary_image

        lines.append(
            "INSERT INTO product (id, brand_id, name, slug, description, short_description, primary_image_url, is_featured, is_active, created_at, updated_at) "
            f"VALUES ({product_id}, {mapped_brand_id}, '{esc(title)}', '{esc(slug)}', {desc_sql}, {short_sql}, {img_sql}, {featured}, {active}, {TS}, {TS});\n"
        )

        categories_for_product = p.get("categories") or []
        for pc in categories_for_product:
            source_cat_id = int(pc["id"])
            mapped_cat_id = category_id_map.get(source_cat_id)
            if mapped_cat_id is not None:
                lines.append(
                    f"INSERT INTO product_category (product_id, category_id) VALUES ({product_id}, {mapped_cat_id});\n"
                )

        prices = p.get("prices") or {}
        regular_price = cents_to_decimal(prices.get("regular_price") or prices.get("price"))
        sale_price_raw = prices.get("sale_price")
        sale_price = cents_to_decimal(sale_price_raw) if sale_price_raw and sale_price_raw != prices.get("regular_price") else None
        sale_sql = "NULL" if not sale_price else sale_price

        sku = str(p.get("sku") or "").strip() or f"BH-{source_product_id}"
        if sku in sku_used:
            sku = f"{sku}-{product_id}"
        sku_used.add(sku)

        lines.append(
            "INSERT INTO product_variant (id, product_id, sku, name, regular_price, sale_price, is_default, created_at, updated_at) "
            f"VALUES ({variant_id}, {product_id}, '{esc(sku)}', 'Default', {regular_price}, {sale_sql}, true, {TS}, {TS});\n"
        )

        in_stock = bool(p.get("is_in_stock"))
        qty = 12 if in_stock else 0
        for location in LOCATIONS:
            lines.append(
                "INSERT INTO inventory (id, product_variant_id, store_location_id, quantity, created_at, updated_at) "
                f"VALUES ({inventory_id}, {variant_id}, {location.id}, {qty}, {TS}, {TS});\n"
            )
            inventory_id += 1

        product_id += 1
        variant_id += 1

    for bid in sorted(brand_logo_url.keys()):
        lines.append(
            f"UPDATE brand SET logo_url = '{esc(brand_logo_url[bid])}' WHERE id = {bid};\n"
        )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(lines), encoding="utf-8")
    print(
        f"Wrote {OUT} with {len(brands) + 1} brands, {len(categories)} categories, "
        f"{len(products)} products, {len(products)} variants."
    )


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Writes db/changelog/sql/catalog-seed.sql for B04 (55 products, variants, inventory)."""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/main/resources/db/changelog/sql/catalog-seed.sql"
TS = "TIMESTAMP '2026-01-01 12:00:00'"


def esc(s: str) -> str:
    return s.replace("'", "''")


def main() -> None:
    lines: list[str] = []
    lines.append("-- B04 catalog seed (generated by scripts/generate_catalog_seed.py)\n")

    for i in range(1, 4):
        lines.append(
            f"INSERT INTO store_location (id, name, slug, is_active, created_at, updated_at) "
            f"VALUES ({i}, '{esc('Magacin ' + str(i))}', 'magacin-{i}', true, {TS}, {TS});\n"
        )

    brands = ["GlowLab", "PureSkin", "HairLux", "BioFit", "DermaCo", "Naturelle"]
    for i, name in enumerate(brands, 1):
        slug = name.lower()
        lines.append(
            f"INSERT INTO brand (id, name, slug, created_at, updated_at) VALUES ({i}, '{esc(name)}', '{slug}', {TS}, {TS});\n"
        )

    cats = [
        (1, "Šminka", "sminka", None, 10),
        (2, "Nega kože", "nega-koze", None, 20),
        (3, "Usne", "usne", 1, 30),
        (4, "Oči", "oci", 1, 40),
        (5, "Ten", "ten", 1, 50),
        (6, "Krema", "krema", 2, 60),
        (7, "Serum", "serum", 2, 70),
        (8, "Čišćenje", "ciscenje", 2, 80),
        (9, "Mat ruževi", "mat-ruzevi", 3, 90),
        (10, "Noćna nega", "nocna-nega", 6, 100),
    ]
    for cid, name, slug, parent, so in cats:
        p = "NULL" if parent is None else str(parent)
        lines.append(
            f"INSERT INTO category (id, name, slug, description, parent_category_id, sort_order, is_active, created_at, updated_at) "
            f"VALUES ({cid}, '{esc(name)}', '{slug}', NULL, {p}, {so}, true, {TS}, {TS});\n"
        )

    for i in range(1, 56):
        bid = (i % 6) + 1
        slug = f"product-{i:03d}"
        feat = "true" if i % 11 == 0 else "false"
        lines.append(
            f"INSERT INTO product (id, brand_id, name, slug, description, short_description, primary_image_url, is_featured, is_active, created_at, updated_at) "
            f"VALUES ({i}, {bid}, '{esc('Proizvod ' + str(i))}', '{slug}', '{esc('Opis proizvoda ' + str(i))}.', '{esc('Kratko ' + str(i))}.', NULL, {feat}, true, {TS}, {TS});\n"
        )

    for i in range(1, 56):
        cid = (i % 10) + 1
        lines.append(f"INSERT INTO product_category (product_id, category_id) VALUES ({i}, {cid});\n")

    variant_to_product: dict[int, int] = {}
    variant_id = 1
    option_value_id = 1

    # Products 1-10: Size option + 3 variants
    pvo_rows: list[tuple[int, int]] = []
    for pid in range(1, 11):
        lines.append(
            f"INSERT INTO product_option (id, product_id, name, sort_order) VALUES ({pid}, {pid}, 'Veličina', 1);\n"
        )
        vids: list[int] = []
        for val, so in [("S", 1), ("M", 2), ("L", 3)]:
            lines.append(
                f"INSERT INTO product_option_value (id, product_option_id, option_value, sort_order) "
                f"VALUES ({option_value_id}, {pid}, '{val}', {so});\n"
            )
            vids.append(option_value_id)
            option_value_id += 1
        labels = ["S", "M", "L"]
        for idx, ovid in enumerate(vids):
            sku = f"P{pid:03d}-{labels[idx]}"
            reg = 1000 + pid * 10 + idx
            sale = "NULL" if pid % 5 != 0 else f"{round(reg * 0.85, 2):.2f}"
            is_def = idx == 0
            lines.append(
                f"INSERT INTO product_variant (id, product_id, sku, name, regular_price, sale_price, is_default, created_at, updated_at) "
                f"VALUES ({variant_id}, {pid}, '{sku}', '{esc('Varijanta ' + labels[idx])}', {reg}.00, {sale}, {str(is_def).lower()}, {TS}, {TS});\n"
            )
            variant_to_product[variant_id] = pid
            pvo_rows.append((variant_id, ovid))
            variant_id += 1

    # Products 11-30: two variants
    for pid in range(11, 31):
        for j in range(2):
            sku = f"P{pid:03d}-V{j + 1}"
            reg = 800 + pid * 5 + j * 3
            sale = "NULL" if pid % 7 != 0 else f"{round(reg * 0.9, 2):.2f}"
            is_def = j == 0
            lines.append(
                f"INSERT INTO product_variant (id, product_id, sku, name, regular_price, sale_price, is_default, created_at, updated_at) "
                f"VALUES ({variant_id}, {pid}, '{sku}', '{esc('Varijanta ' + str(j + 1))}', {reg}.00, {sale}, {str(is_def).lower()}, {TS}, {TS});\n"
            )
            variant_to_product[variant_id] = pid
            variant_id += 1

    # Products 31-55: single variant
    for pid in range(31, 56):
        sku = f"P{pid:03d}-DEF"
        reg = 600 + pid * 4
        sale = "NULL" if pid % 6 != 0 else f"{round(reg * 0.88, 2):.2f}"
        lines.append(
            f"INSERT INTO product_variant (id, product_id, sku, name, regular_price, sale_price, is_default, created_at, updated_at) "
            f"VALUES ({variant_id}, {pid}, '{sku}', 'Default', {reg}.00, {sale}, true, {TS}, {TS});\n"
        )
        variant_to_product[variant_id] = pid
        variant_id += 1

    max_variant_id = variant_id - 1

    for vid, ovid in pvo_rows:
        lines.append(
            f"INSERT INTO product_variant_option (product_variant_id, product_option_value_id) VALUES ({vid}, {ovid});\n"
        )

    inv_id = 1
    for vid in range(1, max_variant_id + 1):
        pid = variant_to_product[vid]
        oos = pid % 9 == 0
        for loc in range(1, 4):
            qty = 0 if oos else (5 + (vid + loc) % 15)
            lines.append(
                f"INSERT INTO inventory (id, product_variant_id, store_location_id, quantity, created_at, updated_at) "
                f"VALUES ({inv_id}, {vid}, {loc}, {qty}, {TS}, {TS});\n"
            )
            inv_id += 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(lines)} statements)")


if __name__ == "__main__":
    main()
